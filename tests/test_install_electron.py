def _make_source_bundle(
    root: Path,
    *,
    checkout: Path = VIEWER_DIR,
    version: str = VIEWER_VERSION,
) -> Path:
    app = root / "Electron.app"
    executable = app / "Contents" / "MacOS" / "Electron"
    executable.parent.mkdir(parents=True)
    executable.write_text("binary\n")
    executable.chmod(0o755)
    info = app / "Contents" / "Info.plist"
    with info.open("wb") as stream:
        plistlib.dump({"CFBundleName": "vibe-view"}, stream)
    app_dir = app / "Contents" / "Resources" / "app"
    app_dir.mkdir(parents=True)
    main_js = checkout / "electron" / "main.js"
    (app_dir / "launcher.js").write_text(
        "// Generated by install-electron.py -- Dock/double-click launcher.\n"
        "// Loads the real vibe-view app from the source checkout that ran\n"
        "// the installer; re-run install-electron.py if the checkout moves.\n"
        f"// vibe-view {version}\n"
        f"require({json.dumps(str(main_js.resolve()))});\n"
    )
    (app_dir / "package.json").write_text(
        json.dumps(
            {
                "name": "vibe-view-launcher",
                "private": True,
                "version": version,
                "main": "launcher.js",
            }
        )
    )
    (app_dir / "vibe-view-source-app.json").write_text(
        json.dumps(
            {
                "schema": 1,
                "kind": "vibe-view-source-desktop",
                "version": version,
                "electron_version": "33.4.11",
                "checkout": str(checkout.resolve()),
            }
        )
    )
    return app


def _make_direct_download_runtime(
    installer,
    root: Path,
    *,
    version: str = "33.4.11",
) -> Path:
    root.mkdir(parents=True)
    (root / "dist").mkdir()
    (root / "vibe-view-electron-version").write_text(version + "\n")
    for name, payload in installer._npm_wrapper_payloads().items():
        (root / name).write_text(payload)
    return root


