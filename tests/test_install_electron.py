def test_missing_runtime_uses_reviewed_pin(installer, tmp_path: Path, monkeypatch) -> None:
    reviewed_version = installer.configured_electron_version()
    payload = io.BytesIO()
    with zipfile.ZipFile(payload, "w") as archive:
        for name, content, mode in (
            ("electron", f"#!/bin/sh\nprintf 'v{reviewed_version}\\n'\n", 0o755),
            ("chrome_crashpad_handler", "helper\n", 0o755),
            ("chrome-sandbox", "sandbox\n", 0o4755),
        ):
            member = zipfile.ZipInfo(name)
            member.create_system = 3
            member.external_attr = (stat.S_IFREG | mode) << 16
            archive.writestr(member, content)
        archive.writestr("version", reviewed_version + "\n")
    payload.seek(0)

    class Response:
        headers = {"content-length": str(len(payload.getvalue()))}

        def __init__(self):
            self.stream = io.BytesIO(payload.getvalue())

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            return False

        def read(self, size: int = -1):
            return self.stream.read(size)

    requested: list[str] = []

    def download_url(version: str) -> str:
        requested.append(version)
        return f"https://example.invalid/electron-v{version}-linux-x64.zip"

    monkeypatch.setattr(installer, "get_download_url", download_url)
    monkeypatch.setattr(
        installer.urllib.request,
        "urlopen",
        lambda _req, **_kwargs: Response(),
    )
    monkeypatch.setattr(installer, "verify_download_checksum", lambda *_args: None)
    monkeypatch.setattr(installer.platform, "system", lambda: "Linux")
    monkeypatch.setattr(installer.shutil, "which", lambda _name: None)
    monkeypatch.setattr(
        installer,
        "finalize_electron_install",
        lambda *_args, **_kwargs: "not-applicable",
    )
    target = tmp_path / "electron"

    installer.install_electron(target_dir=str(target))

    assert requested == [reviewed_version]
    assert (target / "dist" / "electron").exists()
    assert stat.S_IMODE((target / "dist" / "chrome_crashpad_handler").stat().st_mode) == 0o755
    assert stat.S_IMODE((target / "dist" / "chrome-sandbox").stat().st_mode) == 0o4755
    assert (target / "vibe-view-electron-version").read_text() == reviewed_version + "\n"


def test_runtime_record_swap_failure_restores_previous_install(
    installer,
    tmp_path: Path,
    monkeypatch,
) -> None:
    payload = io.BytesIO()
    with zipfile.ZipFile(payload, "w") as archive:
        archive.writestr("electron", "#!/bin/sh\nprintf 'v33.4.11\\n'\n")
        archive.writestr("version", "33.4.11\n")

    class Response:
        headers = {"content-length": str(len(payload.getvalue()))}

        def __init__(self):
            self.stream = io.BytesIO(payload.getvalue())

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            return False

        def read(self, size: int = -1):
            return self.stream.read(size)

    target = tmp_path / "electron"
    old_dist = target / "dist"
    old_dist.mkdir(parents=True)
    (old_dist / "keep.txt").write_text("old runtime\n")
    version_record = target / "vibe-view-electron-version"
    version_record.write_text("32.0.0\n")

    monkeypatch.setattr(
        installer,
        "get_download_url",
        lambda version: f"https://example.invalid/electron-v{version}-linux-x64.zip",
    )
    monkeypatch.setattr(
        installer.urllib.request,
        "urlopen",
        lambda _req, **_kwargs: Response(),
    )
    monkeypatch.setattr(installer, "verify_download_checksum", lambda *_args: None)
    monkeypatch.setattr(installer.platform, "system", lambda: "Linux")
    monkeypatch.setattr(installer.shutil, "which", lambda _name: None)
    real_replace = installer.os.replace
    failed_record_swap = False

    def fail_first_record_swap(source, destination):
        nonlocal failed_record_swap
        if Path(destination) == version_record and not failed_record_swap:
            failed_record_swap = True
            raise OSError("simulated version-record swap failure")
        return real_replace(source, destination)

    monkeypatch.setattr(installer.os, "replace", fail_first_record_swap)

    with pytest.raises(OSError, match="version-record swap failure"):
        installer.install_electron("33.4.11", target_dir=str(target))

    assert (old_dist / "keep.txt").read_text() == "old runtime\n"
    assert not (old_dist / "electron").exists()
    assert version_record.read_text() == "32.0.0\n"


