def symbol_to_z(symbol: str, default: int = 0) -> int:
    """Look up a canonical-case symbol, preserving the caller's unknown policy.

    Format readers decide whether to normalize case or parse atom names;
    for example PDB ``CA`` is not inherently the element calcium.
    """
    return SYMBOL_TO_Z.get(symbol, default)


def z_to_symbol(atomic_number: int, default: str = "X") -> str:
    """Return the H–Cm symbol, or *default* for an unsupported atomic number."""
    return Z_TO_SYMBOL.get(atomic_number, default)


def covalent_radius(atomic_number: int, default: float) -> float:
    """Cordero radius in angstroms, with an explicit caller-owned fallback."""
    return COVALENT_RADII.get(atomic_number, default)


def cpk_hex(atomic_number: int) -> str:
    """Stock Jmol color, or hot pink for unknown elements; no user overrides."""
    return CPK_HEX.get(atomic_number, UNKNOWN_COLOR)


def vdw_radius(atomic_number: int) -> float:
    """Viewer display radius: tabulated, 1.6× covalent, or 1.7 Å if unknown.

    The estimate is the existing ball-and-stick sizing policy. Space-filling
    and export styles may apply their own estimates when no value is tabulated.
    """
    radius = VDW_RADII.get(atomic_number)
    if radius is not None:
        return radius
    covalent = COVALENT_RADII.get(atomic_number)
    return covalent * 1.6 if covalent is not None else 1.7
